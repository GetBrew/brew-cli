import assert from 'node:assert/strict'
import { execFileSync, spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import test from 'node:test'
import { fileURLToPath } from 'node:url'

const checker = fileURLToPath(new URL('./check-comments.mjs', import.meta.url))
function inspect(files, policy = {}) {
  const root = mkdtempSync(join(tmpdir(), 'brew-comments-'))
  try {
    execFileSync('git', ['init', '--quiet', root])
    const put = (file, value) => {
      mkdirSync(join(root, file, '..'), { recursive: true })
      writeFileSync(join(root, file), value)
    }
    put(
      'scripts/comment-ownership.json',
      JSON.stringify({ fixtures: [], generated: [], markers: {}, ...policy })
    )
    for (const [file, value] of Object.entries(files)) put(file, value)
    return spawnSync(process.execPath, [checker, '--root', root], {
      cwd: tmpdir(),
      encoding: 'utf8',
    })
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
}

test('checks owned languages, Markdown examples and MDX expressions', () => {
  const files = {
    'src/example.ts': 'const x=1 // stale',
    'style.css': 'a { color: red; /* stale */ }',
    'ci.yml': 'name: example # stale',
    Dockerfile: 'FROM node:22\n# stale',
    Makefile: '# stale\nall: ; echo ok',
    '.gitignore': '# stale\nnode_modules/',
    'run.sh': 'echo ok # stale',
    'module.py': 'value=1 # stale',
    'lib.rs': 'fn main() {} // stale',
    'page.html':
      '<div><!-- stale --></div><script>const x=1; /* stale */</script>',
    'schema.graphql': 'type Query { value: Int } # stale',
    'query.sql': 'SELECT 1; -- stale',
    'project.toml': 'name="value" # stale',
    'README.md':
      '<!-- stale -->\n\n```ts\nconst x=1 // stale\n```\n\n```bash\necho ok # stale\n```',
    'page.mdx': 'A page\n\n{/* stale */}',
    'raw-html.md':
      '<script>const x=1; /* stale */</script>\n<style>p{color:red;/* stale */}</style>',
    'legacy.html':
      '<script type="text/x-javascript">/* stale */const x=1;</script>',
    'attribute.mdx': '<Component value={1 /* stale */} />',
    'spread.mdx': '<Component {...{/* stale */ value:1}} />',
  }
  const result = inspect(files)
  assert.equal(result.status, 1, result.stderr)
  for (const file of Object.keys(files))
    assert.ok(result.stderr.includes(`${file}:`), result.stderr)
})

test('keeps literals, executable metadata and SQL COMMENT statements', () => {
  const result = inspect({
    'example.tsx':
      '/* globals service */\n/** @jsx h */\n/** @jsxFrag Fragment */\nconst x = <p>// literal</p>; const url="https://brew.new/*literal*/"',
    'style.css': 'a { content: "/* literal */"; }',
    'page.html': '<script type="text/plain">// literal user text</script>',
    '.gitignore': '\\#literal\nnode_modules/',
    Dockerfile: '# syntax=docker/dockerfile:1\nFROM node:22',
    'run.sh': '#!/usr/bin/env bash\nprintf "%s" "# literal"',
    'module.py': 'value = "# literal"',
    'ci.yml': 'value: "# literal"',
    'query.sql':
      "COMMENT ON TABLE example IS 'a description'; SELECT '-- literal';",
    'README.md':
      'Use `<!-- literal -->` and `// literal`.\n\n```ts\nconst x="/* literal */"\n```',
    'page.mdx': 'A page\n\n{"{/* literal */}"}',
  })
  assert.equal(result.status, 0, result.stderr)
})

test('only reviewed ownership paths and exact managed markers are excluded', () => {
  const result = inspect(
    {
      'src/fixtures/example.ts': '// stale',
      'src/example.generated.ts': '// Generated by a tool\n// stale',
      '.agents/skills/local/SKILL.md': '<!-- stale -->',
      'tests/fixtures/evidence.ts': '// recorded evidence',
      'generated/output.ts': '// generated explanation',
      'README.md': '<!-- API:START -->\n<!-- stale -->\n<!-- API:END -->',
    },
    {
      fixtures: ['tests/fixtures/'],
      generated: ['generated/'],
      markers: { 'README.md': ['API:START', 'API:END'] },
    }
  )
  assert.equal(result.status, 1)
  for (const file of [
    'src/fixtures/example.ts',
    'src/example.generated.ts',
    '.agents/skills/local/SKILL.md',
    'README.md',
  ])
    assert.ok(result.stderr.includes(`${file}:`), result.stderr)
  assert.ok(
    !result.stderr.includes('tests/fixtures/evidence.ts:'),
    result.stderr
  )
  assert.ok(!result.stderr.includes('generated/output.ts:'), result.stderr)
  assert.ok(!result.stderr.includes('README.md:1:'), result.stderr)
  assert.ok(!result.stderr.includes('README.md:3:'), result.stderr)
})

test('fails closed for invalid arguments and malformed MDX', () => {
  assert.notEqual(
    spawnSync(process.execPath, [checker, '--unknown'], { encoding: 'utf8' })
      .status,
    0
  )
  const result = inspect({ 'page.mdx': '<Component broken={' })
  assert.equal(result.status, 1)
  assert.ok(result.stderr.includes('unable to inspect comments'), result.stderr)
})
