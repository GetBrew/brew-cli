import assert from 'node:assert/strict'
import test from 'node:test'
import ts from 'typescript'
import {
  findComments,
  isRequiredComment,
  withoutComments,
} from './lib/source-comments.mjs'

test('finds comments without treating literals or JSX text as comments', () => {
  const source = [
    'const url = "https://brew.new/*example*/"',
    'const pattern = /https?:\\/\\//',
    ['const template = `literal // text $', '{1 /* expression */}`'].join(''),
    'const element = <div>// text{/* JSX */}</div>',
    '/** Public explanation. */',
    'export const value = 1 // trailing',
  ].join('\n')
  assert.equal(findComments('example.tsx', source).length, 4)
  const result = withoutComments('example.tsx', source)
  assert.ok(result.includes('https://brew.new/*example*/'))
  assert.ok(result.includes('literal // text'))
  assert.ok(result.includes('<div>// text{'))
  assert.equal(findComments('example.tsx', result).length, 0)
})

test('preserves compiler, lint, coverage, type and legal directives', () => {
  const source = [
    '// @ts-expect-error deliberately invalid input',
    '// biome-ignore lint/suspicious/noExplicitAny: external contract',
    '/* v8 ignore next */',
    '/** @type {string} */',
    '/** @deprecated */',
    '/* eslint no-console: "off" */',
    '/* @vite-ignore */',
    '/*turbopackIgnore: true*/',
    '/** @this {{ answer: number }} */',
    '/** @constructor */',
    '/** @import { Input } from "./input" */',
    '/**\n * @vitest-environment jsdom\n */',
    '/*\n * v8 ignore next\n */',
    '/// <reference types="vite/client" />',
    '/*! Copyright 2026 Brew, MIT License */',
    'const value = 1',
  ].join('\n')
  assert.deepEqual(findComments('example.ts', source), [])
  assert.equal(withoutComments('example.ts', source), source)
})

test('retains newlines that affect automatic semicolon insertion', () => {
  for (const newline of ['\n', '\r', '\u2028', '\u2029']) {
    const source = `function value() { return /* explanation${newline}continues */ 1 }`
    const result = withoutComments('example.ts', source)
    assert.ok(result.includes(newline))
    assert.equal(new Function(`${result}; return value()`)(), undefined)
  }
})

test('keeps generated provenance separate from explanatory source comments', () => {
  const source =
    '// Generated by a build tool.\n// Provenance continuation.\nconst value = 1\n// An explanation.\n'
  assert.equal(findComments('generated.ts', source).length, 3)
  assert.equal(
    findComments(
      'example.ts',
      '/**\n * coverage matrix\n * !important value\n */\nconst value = 1'
    ).length,
    1
  )
})

test('preserves JSDoc that supplies the JavaScript this type', () => {
  const source =
    '/** @this {{answer:number}} */\nfunction answer() { return this.answer }'
  const diagnostics = (input) => {
    const options = {
      allowJs: true,
      checkJs: true,
      noImplicitThis: true,
      noLib: true,
      noEmit: true,
    }
    const host = ts.createCompilerHost(options)
    host.getSourceFile = (file) =>
      file === 'example.js'
        ? ts.createSourceFile(
            file,
            input,
            ts.ScriptTarget.Latest,
            true,
            ts.ScriptKind.JS
          )
        : undefined
    return ts
      .createProgram(['example.js'], options, host)
      .getSemanticDiagnostics()
      .map((diagnostic) => diagnostic.code)
  }
  assert.deepEqual(diagnostics(withoutComments('example.js', source)), [])
  assert.ok(
    diagnostics('function answer() { return this.answer }').includes(2683)
  )
})

test('preserves compiler-defined JSDoc contracts and fragment pragmas', () => {
  const options = {
    allowJs: true,
    checkJs: true,
    noLib: true,
    noEmit: true,
    target: ts.ScriptTarget.ES2022,
  }
  const diagnostics = (source) => {
    const host = ts.createCompilerHost(options)
    host.getSourceFile = (file) =>
      file === 'sample.js'
        ? ts.createSourceFile(
            file,
            source,
            ts.ScriptTarget.Latest,
            true,
            ts.ScriptKind.JS
          )
        : undefined
    return ts
      .createProgram(['sample.js'], options, host)
      .getSemanticDiagnostics()
      .map((diagnostic) => diagnostic.code)
  }
  for (const [tag, code] of [
    ['private', 2341],
    ['protected', 2445],
    ['readonly', 2540],
    ['override', 4121],
  ]) {
    const source = `class C {\n/** @${tag} */\nvalue = 1\n}\nconst x = new C();\nx.value = 2;`
    assert.ok(diagnostics(source).includes(code))
    assert.deepEqual(
      diagnostics(withoutComments('sample.js', source)),
      diagnostics(source)
    )
  }
  const fragment =
    '/** @jsx h */\n/** @jsxFrag Fragment */\nconst value = <><span /></>'
  const emit = (source) =>
    ts.transpileModule(source, {
      fileName: 'sample.tsx',
      compilerOptions: { jsx: ts.JsxEmit.React, removeComments: true },
    }).outputText
  assert.equal(emit(withoutComments('sample.tsx', fragment)), emit(fragment))
  assert.ok(isRequiredComment('/* @ts-self-types="./canvas_engine.d.ts" */'))
  assert.ok(isRequiredComment('/* globals service */'))
})

test('does not exempt prose merely mentioning type tags or generators', () => {
  assert.equal(
    findComments('example.ts', '// TODO @import this is stale\nconst x=1')
      .length,
    1
  )
  assert.equal(
    findComments('example.ts', '/** @example x() */\nconst x=1').length,
    1
  )
})

test('preserves raw internal annotations used by declaration emit', () => {
  const emit = (source) => {
    const options = {
      declaration: true,
      emitDeclarationOnly: true,
      stripInternal: true,
      noLib: true,
    }
    const host = ts.createCompilerHost(options)
    host.getSourceFile = (file) =>
      file === 'sample.ts'
        ? ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true)
        : undefined
    let output = ''
    host.writeFile = (_file, value) => {
      output += value
    }
    ts.createProgram(['sample.ts'], options, host).emit()
    return output
  }
  for (const marker of [
    '// @internal',
    '/* @internal */',
    '/** @internal */',
  ]) {
    const source = `${marker}\nexport const hidden = 1\nexport const visible = 2`
    assert.equal(emit(withoutComments('sample.ts', source)), emit(source))
    assert.ok(!emit(source).includes('hidden'))
    assert.ok(emit(source).includes('visible'))
  }
})

test('recognizes executable lint declarations and rejects prose annotations', () => {
  for (const value of [
    '/* global service:readonly, other:writable */',
    '/* exported exposed */',
    '// billing-exempt: internal lab',
  ])
    assert.ok(isRequiredComment(value))
  for (const value of [
    '// global state is shared',
    '// exported from the `sends` block above',
    '/* exported from the block above */',
    '/** @throws {Error} Something failed */',
  ])
    assert.ok(!isRequiredComment(value))
})
