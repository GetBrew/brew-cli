test('preserves JSDoc that supplies the JavaScript this type', () => {
  const source =
    '/** @this {{answer:number}} */\nfunction answer() { return this.answer }'
  const diagnostics = (input) => {
    const options = {
      allowJs: true,
      checkJs: true,
      noImplicitThis: true,
      noLib: true,
      noEmit: true,
    }
    const host = ts.createCompilerHost(options)
    host.getSourceFile = (file) =>
      file === 'example.js'
        ? ts.createSourceFile(
            file,
            input,
            ts.ScriptTarget.Latest,
            true,
            ts.ScriptKind.JS
          )
        : undefined
    return ts
      .createProgram(['example.js'], options, host)
      .getSemanticDiagnostics()
      .map((diagnostic) => diagnostic.code)
  }
  assert.deepEqual(diagnostics(withoutComments('example.js', source)), [])
  assert.ok(
    diagnostics('function answer() { return this.answer }').includes(2683)
  )
})

test('preserves compiler-defined JSDoc contracts and fragment pragmas', () => {
  const options = {
    allowJs: true,
    checkJs: true,
    noLib: true,
    noEmit: true,
    target: ts.ScriptTarget.ES2022,
  }
  const diagnostics = (source) => {
    const host = ts.createCompilerHost(options)
    host.getSourceFile = (file) =>
      file === 'sample.js'
        ? ts.createSourceFile(
            file,
            source,
            ts.ScriptTarget.Latest,
            true,
            ts.ScriptKind.JS
          )
        : undefined
    return ts
      .createProgram(['sample.js'], options, host)
      .getSemanticDiagnostics()
      .map((diagnostic) => diagnostic.code)
  }
  for (const [tag, code] of [
    ['private', 2341],
    ['protected', 2445],
    ['readonly', 2540],
    ['override', 4121],
  ]) {
    const source = `class C {\n/** @${tag} */\nvalue = 1\n}\nconst x = new C();\nx.value = 2;`
    assert.ok(diagnostics(source).includes(code))
    assert.deepEqual(
      diagnostics(withoutComments('sample.js', source)),
      diagnostics(source)
    )
  }
  const fragment =
    '/** @jsx h */\n/** @jsxFrag Fragment */\nconst value = <><span /></>'
  const emit = (source) =>
    ts.transpileModule(source, {
      fileName: 'sample.tsx',
      compilerOptions: { jsx: ts.JsxEmit.React, removeComments: true },
    }).outputText
  assert.equal(emit(withoutComments('sample.tsx', fragment)), emit(fragment))
  assert.ok(isRequiredComment('/* @ts-self-types="./canvas_engine.d.ts" */'))
  assert.ok(isRequiredComment('/* globals service */'))
})

