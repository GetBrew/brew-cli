import assert from 'node:assert/strict'
import test from 'node:test'
import ts from 'typescript'
import { findComments, withoutComments } from './lib/source-comments.mjs'

test('finds comments without treating literals or JSX text as comments', () => {
  const source = [
    'const url = "https://brew.new/*example*/"',
    'const pattern = /https?:\\/\\//',
    ['const template = `literal // text $', '{1 /* expression */}`'].join(''),
    'const element = <div>// text{/* JSX */}</div>',
    '/** Public explanation. */',
    'export const value = 1 // trailing',
  ].join('\n')
  assert.equal(findComments('example.tsx', source).length, 4)
  const result = withoutComments('example.tsx', source)
  assert.ok(result.includes('https://brew.new/*example*/'))
  assert.ok(result.includes('literal // text'))
  assert.ok(result.includes('<div>// text{'))
  assert.equal(findComments('example.tsx', result).length, 0)
})

test('preserves compiler, lint, coverage, type and legal directives', () => {
  const source = [
    '// @ts-expect-error deliberately invalid input',
    '// biome-ignore lint/suspicious/noExplicitAny: external contract',
    '/* v8 ignore next */',
    '/** @type {string} */',
    '/** @deprecated */',
    '/* eslint no-console: "off" */',
    '/* @vite-ignore */',
    '/*turbopackIgnore: true*/',
    '/** @this {{ answer: number }} */',
    '/** @constructor */',
    '/** @import { Input } from "./input" */',
    '/**\n * @vitest-environment jsdom\n */',
    '/*\n * v8 ignore next\n */',
    '/// <reference types="vite/client" />',
    '/*! Copyright 2026 Brew, MIT License */',
    'const value = 1',
  ].join('\n')
  assert.deepEqual(findComments('example.ts', source), [])
  assert.equal(withoutComments('example.ts', source), source)
})

test('retains newlines that affect automatic semicolon insertion', () => {
  for (const newline of ['\n', '\r', '\u2028', '\u2029']) {
    const source = `function value() { return /* explanation${newline}continues */ 1 }`
    const result = withoutComments('example.ts', source)
    assert.ok(result.includes(newline))
    assert.equal(new Function(`${result}; return value()`)(), undefined)
  }
})

test('keeps generated provenance separate from explanatory source comments', () => {
  const source =
    '// Generated by a build tool.\n// Provenance continuation.\nconst value = 1\n// An explanation.\n'
  assert.equal(findComments('generated.ts', source).length, 1)
  assert.equal(
    findComments(
      'example.ts',
      '/**\n * coverage matrix\n * !important value\n */\nconst value = 1'
    ).length,
    1
  )
})

test('preserves JSDoc that supplies the JavaScript this type', () => {
  const source =
    '/** @this {{answer:number}} */\nfunction answer() { return this.answer }'
  const diagnostics = (input) => {
    const options = {
      allowJs: true,
      checkJs: true,
      noImplicitThis: true,
      noLib: true,
      noEmit: true,
    }
    const host = ts.createCompilerHost(options)
    host.getSourceFile = (file) =>
      file === 'example.js'
        ? ts.createSourceFile(
            file,
            input,
            ts.ScriptTarget.Latest,
            true,
            ts.ScriptKind.JS
          )
        : undefined
    return ts
      .createProgram(['example.js'], options, host)
      .getSemanticDiagnostics()
      .map((diagnostic) => diagnostic.code)
  }
  assert.deepEqual(diagnostics(withoutComments('example.js', source)), [])
  assert.ok(
    diagnostics('function answer() { return this.answer }').includes(2683)
  )
})
