import fs from 'node:fs'
import openapiTS, { astToString } from 'openapi-typescript'
import ts from 'typescript'
import { parse } from 'yaml'

/**
 * Wraps the openapi-typescript CLI invocation this repo used before, for one
 * reason: `SendPayloadValue` is a self-referencing UNION. Emitted
 * inline as an interface member (`components["schemas"][...]` indexed
 * access inside its own union), TypeScript resolves the union eagerly and
 * fails with TS2502. The same recursion is legal as a standalone type
 * alias, so we inject the alias and point the schema member at it.
 * Everything else generates exactly as the CLI did
 * (`--default-non-nullable false`).
 */

const RECURSIVE_PAYLOAD_SCHEMA = '#/components/schemas/SendPayloadValue'

const INJECTED_ALIAS = `/**
 * JSON template data for sends (the \`payload\` field on \`POST /v1/sends\`):
 * scalars, null, and arbitrarily nested arrays/objects. Scalar keys resolve
 * legacy {{ tag | fallback }} merge tags; the full tree renders via Liquid
 * as trigger.* / payload.* on Liquid-enabled workspaces. Caps enforced by
 * the API: 64 KiB serialized, 10 container levels, 250 items per array,
 * 100 top-level keys.
 */
export type SendPayloadValue =
  | string
  | number
  | boolean
  | null
  | SendPayloadValue[]
  | { [key: string]: SendPayloadValue };
`

const specUrl = new URL('../openapi/public-api-v1.yaml', import.meta.url)
const outUrl = new URL('../src/generated/openapi-types.ts', import.meta.url)

const ast = await openapiTS(specUrl, {
  defaultNonNullable: false,
  inject: INJECTED_ALIAS,
  transform(_schemaObject, options) {
    if (options.path === RECURSIVE_PAYLOAD_SCHEMA) {
      return ts.factory.createTypeReferenceNode('SendPayloadValue')
    }
  },
})

fs.writeFileSync(outUrl, astToString(ast))
console.log(`wrote ${outUrl.pathname}`)

/*
 * The top-level keys each operation takes (path and query parameters plus
 * JSON body properties), for the unknown-`--input`-key check in
 * `src/lib/input-keys.ts`. An operation whose body is open (an array,
 * `additionalProperties`, or not JSON) is left out, so its input is never
 * refused.
 */
const keysUrl = new URL('../src/generated/input-keys.ts', import.meta.url)
const doc = parse(fs.readFileSync(specUrl, 'utf8'))

function resolve(node) {
  let current = node
  while (current?.$ref) {
    current = current.$ref
      .slice(2)
      .split('/')
      .reduce((parent, key) => parent[key], doc)
  }
  return current
}

/** Body property names, or null when the body takes keys it does not list. */
function bodyKeys(schemaNode, seen = new Set()) {
  const schema = resolve(schemaNode)
  if (schema === undefined || seen.has(schema)) return []
  seen.add(schema)
  const variants = [
    ...(schema.allOf ?? []),
    ...(schema.oneOf ?? []),
    ...(schema.anyOf ?? []),
  ]
  const isOpen =
    (schema.additionalProperties !== undefined &&
      schema.additionalProperties !== false) ||
    (schema.properties === undefined &&
      variants.length === 0 &&
      schema.type !== 'object')
  if (isOpen) return null
  const keys = Object.keys(schema.properties ?? {})
  for (const variant of variants) {
    const nested = bodyKeys(variant, seen)
    if (nested === null) return null
    keys.push(...nested)
  }
  return keys
}

const inputKeys = {}
for (const [path, item] of Object.entries(doc.paths ?? {})) {
  for (const method of ['get', 'post', 'put', 'patch', 'delete']) {
    const operation = item[method]
    if (operation === undefined) continue
    const keys = [...(item.parameters ?? []), ...(operation.parameters ?? [])]
      .map(resolve)
      .filter((param) => param.in === 'path' || param.in === 'query')
      .map((param) => param.name)
    if (operation.requestBody !== undefined) {
      const schema = resolve(operation.requestBody).content?.[
        'application/json'
      ]?.schema
      const body = schema === undefined ? null : bodyKeys(schema)
      if (body === null) continue
      keys.push(...body)
    }
    inputKeys[`${method.toUpperCase()} ${path}`] = [...new Set(keys)].sort()
  }
}

const sorted = Object.fromEntries(
  Object.entries(inputKeys).sort(([a], [b]) => a.localeCompare(b))
)
fs.writeFileSync(
  keysUrl,
  `// Generated by scripts/generate-types.mjs from openapi/public-api-v1.yaml. Do not edit.\n\n/** Top-level input keys per operation (\`METHOD /path\`); open bodies are absent. */\nexport const INPUT_KEYS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(sorted, null, 2)}\n`
)
console.log(`wrote ${keysUrl.pathname}`)
