export type AuthHelperOptions = {
  /** The lifecycle set is set up, so `lifecycle.welcome` exists. */
  readonly lifecycle: boolean
  /** The auth set is set up, so the auth library's keys exist. */
  readonly auth: boolean
}

/**
 * Whether `lib/brew-auth.ts` has anything to say: the auth adapters and the
 * `sendAuthEmail` pass-through always do; a provider that sends its own
 * auth emails only has the welcome helper, so only with the lifecycle set.
 */
export function wantsAuthHelper(
  project: ProjectDetection,
  options: AuthHelperOptions
): boolean {
  return (
    project.auth === 'better-auth' ||
    project.auth === 'authjs' ||
    project.auth === 'none' ||
    options.lifecycle
  )
}

/** `lib/brew-auth.ts`, per auth library. */
export function authHelperFile(
  project: ProjectDetection,
  options: AuthHelperOptions
): string {
  const context: HelperContext = {
    ts: project.typescript,
    workers: project.runtime === 'workers',
  }
  const clientImport = `import { getBrew } from './brew${importSuffix(project)}'`
  const welcome = options.lifecycle ? ['', ...welcomeHelper(context)] : []
  switch (project.auth) {
    case 'better-auth': {
      const after = (project.nextMajor ?? 0) >= 15
      return [
        HEADER,
        "import { brewAuthEmails } from '@brew.new/sdk/better-auth'",
        ...(after ? ["import { after } from 'next/server'"] : []),
        clientImport,
        '',
        '/**',
        " * Better Auth's email callbacks, sent with the starter kit's keys",
        ' * (auth.verify-email, auth.password-reset, auth.email-change,',
        ' * auth.magic-link, auth.otp, lifecycle.welcome). Wire them into',
        ' * betterAuth({ … }): `npx @brew.new/cli init` prints the patch.',
        ...(after
          ? [
              ' * Sends run after the response (`after`), so sign-up never waits on email.',
            ]
          : []),
        ' */',
        // A Worker's client needs the request's `env`: one per request.
        ...(context.workers
          ? [
              `export function createBrewEmails(${envArg(context)}) {`,
              '  return brewAuthEmails({ client: () => getBrew(env) })',
              '}',
            ]
          : [
              'export const brewEmails = brewAuthEmails({',
              '  client: getBrew,',
              ...(after ? ['  waitUntil: after,'] : []),
              '})',
            ]),
        '',
      ].join('\n')
    }
    case 'authjs': {
      const v4 = project.authVersion === 'v4'
      const provider = `BrewEmail({ client: ${context.workers ? '() => getBrew(env)' : 'getBrew'}${v4 ? ", id: 'email'" : ''} })`
      // Without the auth set, no `auth.magic-link` exists to sign in with.
      return [
        HEADER,
        ...(options.auth
          ? ["import { BrewEmail } from '@brew.new/sdk/next-auth'"]
          : []),
        clientImport,
        ...(options.auth
          ? [
              '',
              '/**',
              ' * Auth.js email sign-in through Brew (`auth.magic-link`). Add it to',
              ` * \`providers\` and sign in with signIn('${v4 ? 'email' : 'brew'}', { email }).`,
              ' * Email sign-in needs a database adapter.',
              ' */',
              ...(context.workers
                ? [
                    `export function createBrewEmailProvider(${envArg(context)}) {`,
                    `  return ${provider}`,
                    '}',
                  ]
                : [`export const brewEmailProvider = ${provider}`]),
            ]
          : []),
        ...welcome,
        '',
      ].join('\n')
    }
    case 'none':
      return [
        HEADER,
        ...(context.ts
          ? [
              "import type { BrewSendKey, BrewSendPayloadFor } from '@brew.new/sdk'",
            ]
          : []),
        clientImport,
        '',
        `// ${AUTH_NOTES.none}`,
        '',
        ...sendAuthHelper(context),
        ...welcome,
        '',
      ].join('\n')
    default:
      return [
        HEADER,
        clientImport,
        '',
        `// ${AUTH_NOTES[project.auth]}`,
        ...welcome,
        '',
      ].join('\n')
  }
}

/** `supabase/functions/send-email/index.ts`: the Send Email Hook. */
export function supabaseHookFile(): string {
  return [
    HEADER,
    '// Supabase Auth Send Email Hook: every auth email goes out through Brew.',
    '// Deploy: supabase functions deploy send-email --no-verify-jwt',
    '// Then in Supabase: Authentication > Hooks > Send Email, point it at this',
    "// function's URL and store the secret it shows as SEND_EMAIL_HOOK_SECRET",
    '// (and BREW_API_KEY) in the Edge Function secrets.',
    `import { createBrewClient } from 'npm:${SDK_PACKAGE}@${SDK_RANGE}'`,
    `import { createSupabaseSendEmailHook } from 'npm:${SDK_PACKAGE}@${SDK_RANGE}/supabase'`,
    '',
    'Deno.serve(',
    '  createSupabaseSendEmailHook({',
    "    client: () => createBrewClient({ apiKey: Deno.env.get('BREW_API_KEY') ?? '' }),",
    "    secret: Deno.env.get('SEND_EMAIL_HOOK_SECRET') ?? '',",
    '  })',
    ')',
    '',
  ].join('\n')
}

