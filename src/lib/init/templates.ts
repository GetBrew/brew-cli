/** `ts`, `js`, or `mjs` for a CommonJS JavaScript server (see importSuffix). */
export function sourceExtension(project: ProjectDetection): string {
  return project.typescript
    ? 'ts'
    : importSuffix(project) === '.mjs'
      ? 'mjs'
      : 'js'
}

/**
 * The suffix a relative import needs. Node resolves an Express or Hono
 * server's own imports: with `"type": "module"` it wants `.js`, and a
 * JavaScript server without it loads `.js` as CommonJS, so the generated
 * ES modules there are `.mjs`. Bundlers want none.
 */
export function importSuffix(project: ProjectDetection): string {
  const isNodeServer =
    project.framework === 'express' ||
    project.framework === 'hono' ||
    project.framework === 'node'
  if (!isNodeServer || project.runtime !== 'node') {
    return ''
  }
  return project.esm ? '.js' : project.typescript ? '' : '.mjs'
}

/** A relative import specifier from one root-relative file to another. */
export function relativeImport(
  fromFile: string,
  toFileWithoutExtension: string,
  suffix: string
): string {
  const rel = posix.relative(posix.dirname(fromFile), toFileWithoutExtension)
  return `${rel.startsWith('.') ? rel : `./${rel}`}${suffix}`
}

export function clientPath(project: ProjectDetection): string | null {
  return project.libDir === null
    ? null
    : `${project.libDir}/brew.${sourceExtension(project)}`
}

export function authHelperPath(project: ProjectDetection): string | null {
  return project.libDir === null || project.runtime === 'deno'
    ? null
    : `${project.libDir}/brew-auth.${sourceExtension(project)}`
}

/**
 * Where the payload types and the `brew.send` key registry go: TypeScript
 * projects with server code only (a `.d.ts`-style augmentation means
 * nothing to JavaScript, and Deno resolves `npm:` specifiers instead).
 */
export function contractsPath(project: ProjectDetection): string | null {
  return project.libDir === null ||
    !project.typescript ||
    project.runtime === 'deno'
    ? null
    : `${project.libDir}/brew-contracts.ts`
}

/** `lib/brew.ts`: the lazily created client. */
export function clientFile(project: ProjectDetection): string {
  const ts = project.typescript
  if (project.runtime === 'workers') {
    return [
      HEADER,
      ts
        ? "import { type BrewClient, createBrewClient } from '@brew.new/sdk'"
        : "import { createBrewClient } from '@brew.new/sdk'",
      '',
      ts
        ? 'const clients = new Map<string, BrewClient>()'
        : 'const clients = new Map()',
      '',
      '/**',
      ' * The Brew client for a Worker request: pass `c.env`. BREW_API_KEY is a',
      ' * Worker secret (`wrangler secret put BREW_API_KEY`; `.dev.vars` locally).',
      ' */',
      ts
        ? 'export function getBrew(env: { BREW_API_KEY?: string }): BrewClient {'
        : 'export function getBrew(env) {',
      '  const apiKey = env.BREW_API_KEY',
      "  if (apiKey === undefined || apiKey === '') {",
      "    throw new Error('BREW_API_KEY is not set: run `wrangler secret put BREW_API_KEY`.')",
      '  }',
      '  let client = clients.get(apiKey)',
      '  if (client === undefined) {',
      '    client = createBrewClient({ apiKey })',
      '    clients.set(apiKey, client)',
      '  }',
      '  return client',
      '}',
      '',
    ].join('\n')
  }
  if (project.runtime === 'deno') {
    return [
      HEADER,
      `import { createBrewClient } from 'npm:${SDK_PACKAGE}@${SDK_RANGE}'`,
      '',
      '/** The Brew client for Edge Functions (BREW_API_KEY is a function secret). */',
      'export function getBrew() {',
      "  const apiKey = Deno.env.get('BREW_API_KEY')",
      '  if (!apiKey) {',
      "    throw new Error('BREW_API_KEY is not set: add it to the Edge Function secrets.')",
      '  }',
      '  return createBrewClient({ apiKey })',
      '}',
      '',
    ].join('\n')
  }
  // Where server code finds BREW_API_KEY: SvelteKit and Astro read .env
  // files through Vite, not into process.env.
  const sveltekit = project.framework === 'sveltekit'
  const keyRead =
    project.framework === 'astro'
      ? 'import.meta.env.BREW_API_KEY ?? process.env.BREW_API_KEY'
      : sveltekit
        ? 'env.BREW_API_KEY'
        : 'process.env.BREW_API_KEY'
  return [
    HEADER,
    ts
      ? "import { type BrewClient, createBrewClient } from '@brew.new/sdk'"
      : "import { createBrewClient } from '@brew.new/sdk'",
    ...(sveltekit ? ["import { env } from '$env/dynamic/private'"] : []),
    '',
    ts ? 'let client: BrewClient | undefined' : 'let client',
    '',
    '/**',
    ' * The Brew client for server code, created on first use, so a missing',
    ' * BREW_API_KEY fails the send that needs it rather than the import.',
    ' * Server-only: never import this from code that runs in the browser.',
    ' */',
    ts
      ? 'export function getBrew(): BrewClient {'
      : 'export function getBrew() {',
    '  if (client === undefined) {',
    `    const apiKey = ${keyRead}`,
    "    if (apiKey === undefined || apiKey === '') {",
    "      throw new Error('BREW_API_KEY is not set: add it to .env.local (npx @brew.new/cli init writes it).')",
    '    }',
    '    client = createBrewClient({ apiKey })',
    '  }',
    '  return client',
    '}',
    '',
  ].join('\n')
}

type HelperContext = {
  readonly ts: boolean
  /** Workers: helpers take the request's `env` first. */
  readonly workers: boolean
}

/** The Worker request's `env`, as a parameter. */
function envArg(context: HelperContext): string {
  return context.ts ? 'env: { BREW_API_KEY?: string }' : 'env'
}

function envParam(context: HelperContext): string {
  return context.workers ? `${envArg(context)}, ` : ''
}

function brewCall(context: HelperContext): string {
  return context.workers ? 'getBrew(env)' : 'getBrew()'
}

/** The welcome-email helper (only when the lifecycle set is set up). */
function welcomeHelper(context: HelperContext): string[] {
  const { ts } = context
  return [
    '/**',
    ' * Send `lifecycle.welcome` once per user (the idempotency key is the user',
    ' * id, so a retried sign-up never sends twice).',
    ' */',
    ts
      ? `export async function sendWelcomeEmail(${envParam(context)}user: {`
      : `export async function sendWelcomeEmail(${envParam(context)}user) {`,
    ...(ts
      ? [
          '  id: string',
          '  email: string',
          '  name?: string | null',
          '}): Promise<void> {',
        ]
      : []),
    `  await ${brewCall(context)}.send(`,
    "    'lifecycle.welcome',",
    '    { email: user.email, ...(user.name ? { userName: user.name } : {}) },',
    // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source, a template literal on purpose
    '    { idempotencyKey: `lifecycle.welcome:${user.id}` }',
    '  )',
    '}',
  ]
}

/** A typed pass-through for the auth keys, for apps without an auth library. */
function sendAuthHelper(context: HelperContext): string[] {
  const { ts } = context
  return [
    '/**',
    ' * Send a starter kit auth email by key, e.g.',
    // biome-ignore lint/suspicious/noTemplateCurlyInString: generated source, a template literal on purpose
    " * sendAuthEmail('auth.password-reset', { email, confirmationUrl }, `auth.password-reset:${tokenId}`).",
    ' * Derive the idempotency key from the token so a retry never sends twice.',
    ' */',
    ...(ts
      ? [
          'export async function sendAuthEmail<K extends BrewSendKey>(',
          ...(context.workers ? ['  env: { BREW_API_KEY?: string },'] : []),
          '  key: K,',
          '  payload: BrewSendPayloadFor<K>,',
          '  idempotencyKey?: string',
          '): Promise<void> {',
        ]
      : [
          `export async function sendAuthEmail(${envParam(context)}key, payload, idempotencyKey) {`,
        ]),
    `  await ${brewCall(context)}.send(`,
    '    key,',
    '    payload,',
    '    idempotencyKey === undefined ? undefined : { idempotencyKey }',
    '  )',
    '}',
  ]
}

