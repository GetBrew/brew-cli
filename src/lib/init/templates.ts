/**
 * The files `init` writes into an app. Each template is deterministic (same
 * detection, same bytes), so a re-run finds them `unchanged` and the hashes
 * in `brew.json` keep matching. Every file is create-only: once someone
 * edits one, init leaves it alone.
 */

/** The SDK range generated code and the install step ask for. */
// The first SDK release with `appEmails` and the auth adapter subpaths
// (GetBrew/typescript-sdk#64, planned 13.6.0, on top of #55's `send` in
// 13.5.0; see the app email SDK gate in RELEASING.md). Generated code uses
// the adapters, so it needs 13.6.0. npm's 13.3.0 has none of them.
export const SDK_RANGE = '^13.6.0'
export const SDK_PACKAGE = '@brew.new/sdk'

/**
 * Whether a declared `@brew.new/sdk` range already reaches SDK_RANGE. An
 * older one lacks the imports and calls the generated code makes, so init
 * and migrate install SDK_RANGE over it.
 */
export function reachesSdkRange(declared: string | null | undefined): boolean {
  const version = rangeVersion(declared ?? undefined)
  const needed = rangeVersion(SDK_RANGE)
  return (
    version !== null &&
    needed !== null &&
    (version[0] > needed[0] ||
      (version[0] === needed[0] && version[1] >= needed[1]))
  )
}

