/** The `AGENTS.md` block: how agents in this repo send app email. */
export function agentsBlock(input: {
  readonly project: ProjectDetection
  readonly keys: readonly string[]
  readonly files: {
    readonly client: string | null
    readonly auth: string | null
    readonly contracts: string | null
  }
  readonly skillPaths: readonly string[]
}): string {
  const { files } = input
  const lines = ['## Brew (app email)', '']
  if (files.client !== null) {
    lines.push(
      `This app sends email through Brew: server code calls \`getBrew().send(key, payload)\` from \`${files.client}\`${files.auth === null ? '' : ` (auth and welcome helpers in \`${files.auth}\`)`}.`
    )
  } else if (input.project.runtime === 'deno' || input.project.hasSupabaseDir) {
    lines.push(
      `This app sends auth email through Brew from Supabase Edge Functions (\`${SUPABASE_FUNCTION_PATH}\`).`
    )
  } else {
    lines.push(
      'This app sends email through Brew from its server: call `brew.send(key, payload)` from `@brew.new/sdk` there, never from browser code.'
    )
  }
  if (files.contracts !== null) {
    lines.push(
      `Payload types and the key registry live in \`${files.contracts}\`; regenerate with \`${PROJECT_COMMAND} types --out ${files.contracts}\`.`
    )
  }
  lines.push('')
  if (input.keys.length > 0) {
    lines.push(`- Keys: ${input.keys.map((key) => `\`${key}\``).join(', ')}.`)
  }
  lines.push(
    '- `BREW_API_KEY` is in `.env.local` (git-ignored). Never give it a `NEXT_PUBLIC_`, `VITE_` or `PUBLIC_` name.',
    '- Until a sending domain verifies, app emails reach members of the Brew organization only (sandbox).',
    `- A new email: \`${PROJECT_COMMAND} app-emails upsert <key> --source-file <file> --yes\`, then send it by key.`,
    `- Re-run \`${PROJECT_COMMAND} init\` to update; it never overwrites files you changed.`
  )
  for (const path of input.skillPaths) {
    lines.push(`- Skill: \`${path}\`.`)
  }
  return lines.join('\n')
}

